import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(process.argv[2]);
const load=(name)=>import(pathToFileURL(path.join(root,'dist',name)));
const config=await load('sheets_config.js');
const client=await load('coordinator_client.js');
const browser=await load('sheet_sync_browser.js');
const store=await load('store.js');
const core=await load('sheet_sync_core.js');
assert.equal(config.SHEET_ID,'15Nntilky9pyv1OrQMyOd6k97DsE_tU7I4aJtISQdL2M');
assert.equal(config.COORDINATOR_ENABLED,false);
assert.equal(client.coordinatorReady(),false);
assert.equal(browser.parseSheetId(config.SHEET_ID),config.SHEET_ID);
assert.throws(()=>browser.parseSheetId('1ZWow3SHWxgy-j7s3GWTJd1AxYXQb-E-ca_GTgK2_5CA'),/Destino diferente/);
await assert.rejects(browser.uploadNewRows(config.SHEET_ID,store.emptyDocument()),e=>e.code==='COORDINATOR_REQUIRED');
const envelope={done:true,response:{result:{ok:true,protocol:1,spreadsheetId:config.SHEET_ID,environment:'production'}}};
assert.equal(client.validateCoordinatorResponse(envelope).ok,true);
assert.throws(()=>client.validateCoordinatorResponse({...envelope,response:{result:{...envelope.response.result,environment:'test'}}}),/ambiente/);
const rows=JSON.parse(fs.readFileSync(path.join(root,'testing','fixtures.json'),'utf8'));
const first=core.stageInbound(store.emptyDocument(),rows);
assert.equal(store.validateDocument(first.next),true);
const again=core.stageInbound(first.next,rows);
assert.deepEqual(again.add,{sessions:0,sets:0,exercises:0,exercise_variants:0,weigh_ins:0});
assert.deepEqual(core.planOutbound(first.next,rows),{Treinos:[],Series:[],Peso:[]});
const code=fs.readFileSync(path.join(root,'Code.gs'),'utf8');
assert.ok(code.includes(config.SHEET_ID));
assert.ok(code.includes("result.environment='production'"));
assert.ok(!code.includes('1ZWow3SHWxgy-j7s3GWTJd1AxYXQb-E-ca_GTgK2_5CA'));
const html=fs.readFileSync(path.join(root,'dist','index.html'),'utf8');
const csp=html.match(/connect-src ([^;]+);/)?.[1]||'';
assert.ok(csp.split(/\s+/).includes('https://script.googleapis.com'));
assert.ok(csp.split(/\s+/).includes('https://sheets.googleapis.com'));
assert.ok(!csp.split(/\s+/).includes('*'));
console.log('PRODUCTION_CANDIDATE_TESTS=17');
