import assert from 'node:assert/strict';
import {balancedPlan,replacementFor,movement} from '../dist/principal_variety.js';
const empty={exercises:[],exercise_variants:[],sessions:[],sets:[]};
const plan=(text='costas',extra={})=>balancedPlan(empty,['costas'],text,{today:'2026-10-28',...extra});
const p=plan();
assert.equal(p.items.length,8);
const back=p.items.filter(x=>x.group==='costas');
assert.equal(back.length,4);
assert.equal(new Set(back.map(movement)).size,3);
assert.equal(back.filter(x=>movement(x)==='horizontal').length,2);
assert.equal(new Set(p.items.map(x=>x.name)).size,8);
assert.ok(p.items.every(x=>x.last===null));
assert.ok(plan('costas sem tríceps').items.every(x=>x.group!=='triceps'));
assert.equal(plan('costas',{readiness:{fatigue:'high'}}).items.length,4);
assert.equal(plan('costas',{readiness:{pain:'yes'}}).items.length,0);
const r=replacementFor(p,0);assert.equal(r.group,'costas');assert.ok(!p.items.some(x=>x.name===r.name));
assert.ok(p.items.every(x=>typeof x.movementLabel==='string'));
const legs=balancedPlan(empty,['pernas'],'pernas',{today:'2026-10-28'}).items.filter(x=>x.group==='pernas');assert.ok(new Set(legs.map(movement)).size>=3);
const e={exercises:[{id:'e',name:'Remada baixa'}],exercise_variants:[{id:'v',exercise_id:'e',unit:'kg'}],sessions:[{id:'s',status:'completed',date:'2026-10-27'}],sets:[{id:'set',session_id:'s',exercise_id:'e',variant_id:'v',date:'2026-10-27',set_type:'effective',load_value:25}]};
const before=JSON.stringify(e),known=balancedPlan(e,['costas'],'costas',{today:'2026-10-28'}).items.find(x=>x.variant_id==='v');assert.equal(known.last.load_value,25);assert.equal(JSON.stringify(e),before);
assert.equal(movement({group:'costas',name:'Exercício desconhecido'}),'other');
assert.ok(plan('só costas').items.every(x=>x.group==='costas'));
assert.equal(p.items.find(x=>x.name==='Tríceps na polia').movementLabel,'Extensão de cotovelo');
